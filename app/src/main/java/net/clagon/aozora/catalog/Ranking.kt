/** ランキングでの順位（1 から）。ランキングにない作品は null。 */
fun rankOf(workId: Int) = RANKING_2022.indexOf(workId).takeIf { it >= 0 }?.plus(1)

/** ランキングの上位 limit 件を順位の順に。カタログにない作品は飛ばす。 */
fun CatalogDao.ranking(limit: Int = RANKING_2022.size): Flow<List<WorkItem>> {
    val ids = RANKING_2022.take(limit)
    return workItems(ids).map { items ->
        val byId = items.associateBy { it.id }
        ids.mapNotNull(byId::get)
    }
}
