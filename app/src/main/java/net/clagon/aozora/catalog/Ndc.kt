/** 分野。NDC の第 1 次区分（類）と、その下の第 2 次区分（綱）。 */
class NdcClass(val digit: Int, val name: String, val divisions: List<String>) {
    /** 第 2 次区分の 2 桁の番号（例: "91"）と名前の組 */
    val codes get() = divisions.mapIndexed { i, name -> "$digit$i" to name }
}

