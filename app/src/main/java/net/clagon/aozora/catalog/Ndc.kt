/** 分野の名前。code は NDC の上 1〜3 桁（例: "9"、"91"、"913"）。番号のない区分は空。 */
fun ndcName(code: String): String {
    val digits = code.map(Char::digitToInt)
    return when (digits.size) {
        1 -> NDC_CLASSES[digits[0]].name
        2 -> NDC_CLASSES[digits[0]].divisions[digits[1]]
        else -> SECTIONS[digits[0] * 10 + digits[1]][digits[2]]
    }
}

/** code（上 1〜2 桁）の 1 つ下の区分の番号。番号のない区分は除く。 */
fun ndcChildren(code: String) = (0..9).map { "$code$it" }.filter { ndcName(it).isNotEmpty() }

// 文学（9xx）の 3 桁目が表す文学形式。0 と 9 は形式ではないので null
private val LITERARY_FORMS =
    listOf(null, "詩歌", "戯曲", "小説・物語", "評論・エッセイ・随筆", "日記・書簡・紀行", "記録・手記・ルポルタージュ", "箴言・アフォリズム・寸言", "作品集", null)

/**
 * 作品カードに出すタグ。分類ごとに文学なら形式名、それ以外は第 2 次区分の名前を出す。
 * 分類が 1 つだけのときは、先頭に第 1 次区分の名前（例: 文学）を足す。
 */
fun ndcTags(ndc: String): List<String> {
    val codes = ndc.removePrefix("NDC").split(' ').map { it.removePrefix("K") }
        .filter { it.length == 3 && it.all(Char::isDigit) }
        .map { code -> code.map(Char::digitToInt) }
    val tags = codes.map { (c, d, f) -> LITERARY_FORMS[f].takeIf { c == 9 } ?: NDC_CLASSES[c].divisions[d] }.distinct()
    return if (codes.size == 1) listOf(NDC_CLASSES[codes[0][0]].name) + tags else tags
}

/** 分野ごとの作品数。[CatalogDao.worksByNdc] で出る作品の数と同じになる。 */
class NdcCounts(private val counts: Map<String, Int>) {
    /** code は NDC の上 1〜3 桁。作品のない分野は 0。 */
    fun of(code: String, kidsOnly: Boolean) = counts[if (kidsOnly) "K$code" else code] ?: 0
}

/**
 * 全作品の分類番号（[Work.ndc]）から、すべての分野の作品数を一度に数える。
 * 1 つの作品が同じ分野の分類を複数持っていても 1 件と数える。児童書（K つき）は分野別にも数える。
 */
fun countNdc(ndcs: List<String>): NdcCounts {
    val counts = HashMap<String, Int>()
    for (ndc in ndcs) {
        val keys = HashSet<String>()
        for (token in ndc.removePrefix("NDC").split(' ')) {
            val code = token.removePrefix("K")
            for (n in 1..code.length) {
                keys += code.take(n)
                if (token.startsWith("K")) keys += "K" + code.take(n)
            }
        }
        keys.forEach { counts.merge(it, 1, Int::plus) }
    }
    return NdcCounts(counts)
}

/**
 * 読み（ソート用の値。平仮名・濁点なし）の範囲。from 以上 to 未満を文字コード順で比べる。
 * from が空のときは、平仮名で始まらない読み（記号・英字・片仮名など）を表す。
 */
data class YomiRange(val from: String, val to: String)

private const val HIRAGANA_END = "ゟ" // 平仮名ブロックの末尾。これ以上は片仮名など

/** 平仮名で始まらない読み（作家別の「その他」、作品別の「他」）を表す範囲。 */
private val OTHER_YOMI = YomiRange("", "")

/** 作家別の縦タブに並べる五十音の行。 */
enum class KanaRow(val label: String, val range: YomiRange) {
    A("あ行", YomiRange("ぁ", "か")),
    KA("か行", YomiRange("か", "さ")),
    SA("さ行", YomiRange("さ", "た")),
    TA("た行", YomiRange("た", "な")),
    NA("な行", YomiRange("な", "は")),
    HA("は行", YomiRange("は", "ま")),
    MA("ま行", YomiRange("ま", "や")),
    YA("や行", YomiRange("や", "ら")),
    RA("ら行", YomiRange("ら", "わ")),
    WA("わ行", YomiRange("わ", HIRAGANA_END)),
    OTHER("その他", OTHER_YOMI),
}

/** 作品別で選べる 46 文字を、文字コードの順に並べたもの。[kanaRange] で次の文字を上限にするのに使う。 */
private const val KANA = "あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん"

/** 作品別の格子に 5 列で並べる文字。null は空きマス（や行・わ行の欠け）、「他」は平仮名以外。 */
val KANA_GRID: List<String?> = "あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもや_ゆ_よらりるれろわ_を_ん他"
    .map { if (it == '_') null else it.toString() }

/** その文字で始まる読みの範囲。小書きの仮名などは直前の文字に含める（ソート用の読みにはほぼ出てこない）。 */
fun kanaRange(kana: String): YomiRange {
    val i = KANA.indexOf(kana)
    if (i < 0) return OTHER_YOMI
    val from = if (i == 0) "ぁ" else kana
    val to = if (i == KANA.lastIndex) HIRAGANA_END else KANA[i + 1].toString()
    return YomiRange(from, to)
}
