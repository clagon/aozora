/**
 * 五十音の行。読みのソート用の値（平仮名・濁点なし）を文字コードの範囲で切る。
 * 読みが平仮名で始まらない少数の作品（記号・英字・片仮名など）も漏れないよう、
 * あ行は先頭から、わ行は末尾までを含める。
 */
enum class KanaRow(val label: String, val from: String, val to: String) {
    A("あ", "", "か"),
    KA("か", "か", "さ"),
    SA("さ", "さ", "た"),
    TA("た", "た", "な"),
    NA("な", "な", "は"),
    HA("は", "は", "ま"),
    MA("ま", "ま", "や"),
    YA("や", "や", "ら"),
    RA("ら", "ら", "わ"),
    WA("わ", "わ", "￿"),
}
